/**
 * Wander — Zhich, Yu, Justin
 * Letter shapes for generated handwriting: a single-line print hand.
 *
 * Each glyph is the pen strokes a person would make for that character,
 * in writing order. A stroke is a few control points that the layout joins
 * with a smooth curve. Units: y up, baseline at 0, x-height 1, so capitals
 * and digits are about 1.6 tall, ascenders 1.75 and descenders -0.7. `adv`
 * is the advance width before letter spacing. `delayed` lists strokes that
 * people usually add after finishing the word (i dots, t and f bars).
 */

/** A control point: x and y in x-heights, y up. */
export type GlyphPoint = readonly [number, number];

/** One character's strokes. */
export interface Glyph {
  /** Advance width in x-heights, before letter spacing. */
  adv: number;
  /** Strokes in writing order, each a list of control points. */
  strokes: readonly (readonly GlyphPoint[])[];
  /** Indexes of strokes written after the rest of the word. */
  delayed?: readonly number[];
}

/** Points on an ellipse; angles in degrees, counterclockwise with y up. */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number): GlyphPoint[] {
  const steps = Math.max(4, Math.round(Math.abs(a1 - a0) / 30));
  const out: GlyphPoint[] = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + ((a1 - a0) * i) / steps) * Math.PI) / 180;
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return out;
}

/** A dot: a very short stroke. */
function dot(x: number, y: number): GlyphPoint[] {
  return [
    [x - 0.03, y],
    [x + 0.05, y + 0.05],
  ];
}

/** `pts` scaled by (sx, sy). */
function scaled(pts: readonly GlyphPoint[], sx: number, sy: number): GlyphPoint[] {
  return pts.map(([x, y]) => [x * sx, y * sy]);
}

/** `pts` mirrored left to right within width `w`. */
function mirrored(pts: readonly GlyphPoint[], w: number): GlyphPoint[] {
  return pts.map(([x, y]) => [w - x, y]);
}

/** A figure eight on its side (the infinity sign). */
function lemniscate(): GlyphPoint[] {
  const out: GlyphPoint[] = [];
  for (let i = 0; i <= 16; i++) {
    const t = Math.PI / 2 + (i / 16) * Math.PI * 2;
    const d = 1 + Math.sin(t) ** 2;
    out.push([0.55 + (0.52 * Math.cos(t)) / d, 0.5 + (0.85 * Math.sin(t) * Math.cos(t)) / d]);
  }
  return out;
}

